#!/usr/bin/env node
'use strict';
/**
 * ALDC — build-known-hashes.js
 *
 * Records what previous releases of this toolkit actually wrote, so an upgrade can
 * tell its own untouched content apart from a developer's edit.
 *
 * Releases before 4.3.1 left no installation receipt, so an upgrade sees every
 * differing file as a possible local change and reports it as a collision. With
 * this manifest the installer recognises bytes it shipped itself and replaces them
 * without asking, reserving the question for files that really were edited.
 *
 * Each release is installed for real, from its own tag, into a throwaway project;
 * nothing is inferred from repository sources, because the installer transforms
 * some files as it writes them.
 *
 *   node scripts/build-known-hashes.js [tag ...]     (default: the tags listed below)
 *
 * Run it when cutting a release, then commit the manifest.
 */
const fs = require('fs');
const os = require('os');
const path = require('path');
const crypto = require('crypto');
const { execFileSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const OUTPUT = path.join(ROOT, 'known-installations.json');
const DEFAULT_TAGS = ['v4.2.0'];
const IGNORED = new Set(['.aldc-install', '.git']);

const sha256 = buffer => crypto.createHash('sha256').update(buffer).digest('hex');
const git = args => execFileSync('git', args, { cwd: ROOT, encoding: 'utf8' }).trim();

function walk(root, prefix = '') {
  const out = [];
  for (const entry of fs.readdirSync(path.join(root, prefix), { withFileTypes: true })) {
    if (IGNORED.has(entry.name)) continue;
    const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isSymbolicLink()) continue;
    if (entry.isDirectory()) out.push(...walk(root, rel));
    else if (entry.isFile()) out.push([rel, sha256(fs.readFileSync(path.join(root, rel)))]);
  }
  return out;
}

// One release, installed exactly as its users installed it.
function hashesFor(tag) {
  const worktree = fs.mkdtempSync(path.join(os.tmpdir(), `aldc-${tag}-`));
  const project = fs.mkdtempSync(path.join(os.tmpdir(), 'aldc-project-'));
  try {
    git(['worktree', 'add', '--detach', '--quiet', worktree, tag]);
    const installer = path.join(worktree, 'scripts', 'install.js');
    if (!fs.existsSync(installer)) throw new Error(`${tag}: no scripts/install.js to run`);
    execFileSync(process.execPath, [installer, 'install', '--yes'], { cwd: project, stdio: 'ignore' });
    const written = walk(project);
    if (!written.length) throw new Error(`${tag}: the installer wrote nothing`);
    return written;
  } finally {
    try { git(['worktree', 'remove', '--force', worktree]); } catch { /* already gone */ }
    fs.rmSync(project, { recursive: true, force: true });
    fs.rmSync(worktree, { recursive: true, force: true });
  }
}

function main(tags) {
  const paths = new Map();
  const releases = [];
  for (const tag of tags) {
    const written = hashesFor(tag);
    releases.push({ tag, files: written.length });
    for (const [rel, digest] of written) {
      if (!paths.has(rel)) paths.set(rel, new Set());
      paths.get(rel).add(digest);
    }
    console.log(`${tag}: ${written.length} files`);
  }
  const manifest = {
    schema: 1,
    note: 'Content previous releases wrote, so an upgrade can recognise its own untouched files. Generated by scripts/build-known-hashes.js; never edited by hand.',
    releases,
    paths: Object.fromEntries([...paths].sort(([a], [b]) => a.localeCompare(b)).map(([rel, set]) => [rel, [...set].sort()]))
  };
  fs.writeFileSync(OUTPUT, JSON.stringify(manifest, null, 2) + '\n');
  console.log(`Wrote ${path.relative(ROOT, OUTPUT)}: ${Object.keys(manifest.paths).length} paths from ${releases.length} release(s).`);
}

if (require.main === module) {
  try { main(process.argv.slice(2).length ? process.argv.slice(2) : DEFAULT_TAGS); }
  catch (error) { console.error(error.message); process.exit(1); }
}
module.exports = { hashesFor };
